"""Rebuild nine original creature atlases and one wet Reedrunner cue atlas.

Every pixel is authored by the palettes and motifs below. No downloaded or AI
images are inputs. Run with --check to compare generated bytes without writing.
"""

from __future__ import annotations

import argparse
import math
import struct
import zlib
from pathlib import Path


OUT = Path(__file__).resolve().parents[2] / "src/main/resources/assets/gems/textures/entity"
PALETTES = {
    "inkling": ((37, 54, 91), (223, 223, 198), (84, 127, 165), "ink"),
    "reedrunner": ((38, 92, 88), (106, 172, 146), (219, 205, 117), "wave"),
    "beacon_gull": ((24, 65, 105), (244, 245, 224), (255, 194, 64), "ray"),
    "chorus_hare": ((85, 58, 75), (202, 147, 113), (237, 207, 151), "voice"),
    "cairn_beetle": ((31, 50, 70), (94, 137, 164), (245, 218, 151), "compass"),
    "catalog_owl": ((52, 66, 58), (182, 169, 125), (223, 212, 174), "book"),
    "dust_skipper": ((74, 41, 45), (226, 146, 91), (255, 216, 113), "diamond"),
    "rivet_crab": ((65, 65, 69), (185, 116, 72), (95, 169, 166), "rivet"),
    "splitstone_ram": ((56, 64, 73), (177, 179, 174), (219, 174, 119), "split"),
}


def _chunk(kind: bytes, data: bytes) -> bytes:
    return (struct.pack("!I", len(data)) + kind + data
            + struct.pack("!I", zlib.crc32(kind + data) & 0xFFFFFFFF))


def _png(pixels: list[list[tuple[int, int, int, int]]]) -> bytes:
    scanlines = b"".join(
        b"\x00" + bytes(value for rgba in row for value in rgba)
        for row in pixels
    )
    return (b"\x89PNG\r\n\x1a\n"
            + _chunk(b"IHDR", struct.pack("!2I5B", 64, 64, 8, 6, 0, 0, 0))
            + _chunk(b"IDAT", zlib.compress(scanlines, 9))
            + _chunk(b"IEND", b""))


def render(palette: tuple[tuple[int, int, int], tuple[int, int, int],
                          tuple[int, int, int], str], ready: bool = False) -> bytes:
    dark, base, accent, motif = palette
    pixels = [[(0, 0, 0, 0) for _ in range(64)] for _ in range(64)]

    def put(x: int, y: int, color: tuple[int, int, int]) -> None:
        if 0 <= x < 64 and 0 <= y < 64:
            pixels[y][x] = (*color, 255)

    def rect(x0: int, y0: int, x1: int, y1: int,
             color: tuple[int, int, int]) -> None:
        for y in range(y0, y1):
            for x in range(x0, x1):
                put(x, y, color)

    # UV islands: body, face, feet and the appendage strips.
    for x0, y0, x1, y1 in ((0, 0, 36, 16), (0, 17, 26, 29),
                           (30, 19, 42, 30), (0, 30, 37, 44),
                           (38, 0, 64, 30)):
        rect(x0, y0, x1, y1, dark)
        rect(x0 + 1, y0 + 1, x1 - 1, y1 - 1, base)
        for x in range(x0 + 2, x1 - 2, 5):
            put(x, y0 + 2, accent)

    for x in range(3, 34):
        for y in range(3, 15):
            mark = False
            if motif == "ink":
                mark = (x + y) % 7 == 0 or (y in (6, 11) and x % 4 < 2)
            elif motif == "clock":
                mark = x % 8 == 0 or (y == 7 and x % 3 < 2)
            elif motif == "wave":
                mark = (y + int(2 * math.sin(x / 3))) % 6 == 0
            elif motif == "ray":
                mark = (x - y) % 8 == 0 or (x + y) % 9 == 0
            elif motif == "voice":
                mark = (x // 4 + y // 3) % 3 == 0 and y % 3 == 0
            elif motif == "compass":
                mark = abs(x - 18) == abs(y - 8) * 2 or x == 18 or y == 8
            elif motif == "book":
                mark = y % 5 == 0 and x % 9 != 0
            elif motif == "diamond":
                mark = abs((x % 12) - 6) + abs((y % 10) - 5) == 5
            elif motif == "rivet":
                mark = x % 7 in (0, 1) and y % 5 in (0, 1)
            elif motif == "split":
                mark = (x - y) % 11 == 0 or (x + y) % 11 == 0
            if mark:
                put(x, y, accent)

    for x in (7, 18):
        rect(x, 21, x + 3, 24, dark)
        put(x + 1, 21, accent)
    rect(11, 26, 16, 27, accent)
    for y in range(32, 44, 4):
        for x in range(2, 36):
            if (x + y) % 9 < 3:
                put(x, y, accent)
    for x in range(42, 63, 4):
        for y in range(2, 29):
            if (x * 2 + y) % 13 == 0:
                put(x, y, accent)
    if motif == "ray":
        # A harbor beacon's wings read as pale signal panels with dark tips.
        for x in range(2, 35):
            for y in range(31, 43):
                if x in (2, 33) or (x + 2 * y) % 11 == 0:
                    put(x, y, dark if x in (2, 33) else accent)
        rect(43, 2, 60, 3, accent)
    elif motif == "compass":
        # The larger stepped shell reaches beyond the original small-animal UV strip.
        rect(37, 30, 49, 45, base)
        for x in range(2, 48):
            for y in range(31, 44):
                if y == 37 or (x + y) % 12 == 0:
                    put(x, y, accent)
        rect(21, 34, 27, 40, dark)
        rect(23, 32, 25, 42, accent)
    elif motif == "diamond":
        # Bright ear tips and a band across the raised rear sail stand clear of grass.
        rect(1, 31, 7, 34, accent)
        rect(9, 31, 15, 34, accent)
        rect(43, 5, 61, 7, accent)
    if ready:
        # Pale waterline and luminous reed veins telegraph a harvestable resident.
        assert motif == "wave"
        mint = (188, 244, 217)
        for x in range(3, 34):
            put(x, 9 + int(math.sin(x / 3)), mint)
        for y in range(31, 43):
            put(3 + (y % 3), y, mint)
            put(13 + (y % 4), y, mint)
        rect(43, 8, 61, 10, mint)
    return _png(pixels)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="compare generated PNG bytes without writing files")
    args = parser.parse_args()
    for name, palette in PALETTES.items():
        path = OUT / f"domain_{name}.png"
        image = render(palette)
        if args.check:
            if not path.is_file() or path.read_bytes() != image:
                raise SystemExit(f"Atlas differs: {path}")
        else:
            path.write_bytes(image)
    ready_path = OUT / "domain_reedrunner_ready.png"
    ready_image = render(PALETTES["reedrunner"], ready=True)
    if args.check:
        if not ready_path.is_file() or ready_path.read_bytes() != ready_image:
            raise SystemExit(f"Atlas differs: {ready_path}")
    else:
        ready_path.write_bytes(ready_image)
    print(f"{'Verified' if args.check else 'Generated'} {len(PALETTES)} base atlases and one ready atlas")


if __name__ == "__main__":
    main()
